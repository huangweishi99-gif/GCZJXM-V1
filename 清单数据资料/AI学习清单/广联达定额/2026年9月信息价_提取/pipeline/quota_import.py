def _fix_qty(name: str, qty: float, unit_mult: float, is_length: bool) -> float:
    """丢点修复：高值(整数)超上限→/100迭代；低值(不限整数)<下界/5→×10迭代。
    低值放开非整数——电缆101→10.1 丢一位类失真（高值丢点必成整数，低值可多带一位）。"""
    if a.unit_basis == "m":
        ranges = _QTY_RANGES_PER_M
    else:
        ranges = _QTY_RANGES_M if is_length else _QTY_RANGES_M2
    lo = hi = None
    for kw, r_lo, r_hi in ranges:
        if kw in name:
            lo, hi = r_lo, r_hi
            break
    if lo is None:
        return qty
    if qty != int(qty):
        # 低值×10 仅限安装册（basis=m）：主材 lo~0.9 级，真实消耗不会低于 lo/5；
        # m2 册辅材真实消耗 0.01-0.1 级，放开会误伤（胶0.05→0.5）。
        if a.unit_basis != "m":
            return qty
        v = qty
        for _ in range(2):
            if v < unit_mult * lo / 5:
                v = v * 10
            else:
                break
        return v
    v = qty
    for _ in range(4):
        if v <= unit_mult * hi and v >= unit_mult * lo:
            break
        if v > unit_mult * hi:
            v = v / 100
        else:
            v = v * 10  # 低值（/100 步进过头或非整数丢点）回拉
    return v


def _fix_price(name: str, price) :
    """基期价超品类区间 → /100 一次（机械台班17889=178.89 等）。"""
    if not isinstance(price, (int, float)) or price <= 0:
        return price
    for kw, lo, hi in _PRICE_RANGES:
        if kw in name:
            v = price
            for _ in range(3):
                if v > hi:
                    v = v / 100
                else:
                    break
            return v
    return price


def _infer_unit(section: str) -> str:
    """章节名推断扩大单位（页级单位 OCR 大量缺失，装饰定额按章定单位是强惯例）。"""
    s = section.strip()
    if any(k in s for k in ("线条", "扶手", "栏杆", "弯头", "嵌条", "防滑条",
                            "拦水线", "灯槽", "窗帘盒", "窗帘轨", "波打线", "收口", "门窗套")):
        return "100m"
    if re.search(r"[门窗]$", s):
        return "100樘"
    return "100㎡"


def _row_median_fix(pages):
    """行级一致性修复：同页同材料名在多个子目列都有消耗量，中位数即真值锚。
    离群值（>50×中位 或 <中位/50）按 /10 迭代收敛（最多3次）。在品类物理修复
    之前调用——同行锚比通用区间更直接，避免区间误判（如铁件kg被当t压过头）。"""
    n_fix = 0
    for p in pages:
        by_name = {}
        for it in p.get("items", []):
            for m in it.get("materials", []):
                raw_nm = ((m.get("name") or "").strip() + (m.get("spec") or "").strip()).strip()
                nm = _clean_name(raw_nm)
                q = m.get("qty")
                if nm and isinstance(q, (int, float)) and q > 0:
                    by_name.setdefault(nm, []).append(q)
        med = {}
        for nm, qs in by_name.items():
            if len(qs) >= 2:
                s = sorted(qs)
                med[nm] = s[len(s) // 2]
        for it in p.get("items", []):
            for m in it.get("materials", []):
                raw_nm = ((m.get("name") or "").strip() + (m.get("spec") or "").strip()).strip()
                nm = _clean_name(raw_nm)
                q = m.get("qty")
                if not nm or nm not in med or not isinstance(q, (int, float)) or q <= 0:
                    continue
                mu = med[nm]
                if q > mu * 50 or q < mu / 50:
                    v = q
                    for _ in range(3):
                        if v > mu * 50:
                            v = v / 10
                        elif v < mu / 50:
                            v = v * 10
                        else:
                            break
                    if v != q:
                        m["qty"] = round(v, 6)
                        n_fix += 1
    return n_fix


fix_row_n = _row_median_fix(pages)

items = []
drop_mach = 0
fix_qty_n = 0
fix_price_n = 0
for p in pages:
    section = (p.get("section") or "").strip()
    unit = (p.get("unit") or "").strip() or _infer_unit(section) or a.default_unit
    unit_mult = _unit_mult(unit)
    is_length = unit.startswith("100m") and "2" not in unit and "²" not in unit
    for it in p.get("items", []):
        code = (it.get("code") or "").strip()
        if not code:
            continue
        labor_fee = sum(v for v in it.get("labor", {}).values() if isinstance(v, (int, float)))
        mats = {}
        for m in it.get("materials", []):
            raw_nm = ((m.get("name") or "").strip() + (m.get("spec") or "").strip()).strip()
            if raw_nm.startswith(_MACH_PREFIX) or any(w in raw_nm for w in _MACH_WORDS):
                drop_mach += 1
                continue
            if any(w in raw_nm for w in _FEE_LIKE):
                drop_mach += 1
                continue
            nm = _clean_name(raw_nm)
            qty = m.get("qty")
            if not nm or not isinstance(qty, (int, float)):
                continue
            qty = _fix_qty(nm, float(qty), unit_mult, is_length)
            price = _fix_price(nm, m.get("price"))
            if qty != m.get("qty"):
                fix_qty_n += 1
            if price != m.get("price"):
                fix_price_n += 1
            mats[nm] = [round(float(qty), 4), (m.get("unit_hint") or "").strip(),
                        price if isinstance(price, (int, float)) else None]
        items.append({
            "quota_code": code,
            "name": f"{section}·{code}" if section else code,
            "unit": unit,
            "labor_consumption": round(labor_fee / LABOR_RATE, 4) if labor_fee else 0.0,
            "materials": mats,
            "machinery": {},
            "chapter": section,
            "section": section,
        })

out = {"standard_code": a.standard_code, "standard_name": a.standard_name,
       "quota_items": items}
DST.write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
mat_n = sum(len(it["materials"]) for it in items)
