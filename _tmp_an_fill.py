excel = win32com.client.Dispatch("Excel.Application")
excel.Visible = False
excel.DisplayAlerts = False
try:
    wb = excel.Workbooks.Open(os.path.abspath(SRC))
    n_fill = 0
    rows_by_sheet = {"电气工程": {}, "给排水工程": {}, "空调工程": {}}
    for sn in ["电气工程", "给排水工程", "空调工程"]:
        ws = wb.Sheets(sn)
        maxr = ws.UsedRange.Row + ws.UsedRange.Rows.Count - 1
        for r in range(1, maxr + 1):
            v = ws.Cells(r, 2).Value
            if v is None:
                continue
            if isinstance(v, float) and v.is_integer():
                code = str(int(v))
            else:
                code = str(v).strip()
            if not code:
                continue
            if code in V:
                rows_by_sheet[sn][r] = code
    for sn, rows in rows_by_sheet.items():
        ws = wb.Sheets(sn)
        for r, code in sorted(rows.items()):
            p, q, rr, s, t = V[code]
            ws.Cells(r, 16).Value = p     # P 主材费
            ws.Cells(r, 17).Value = q     # Q 主材损耗率
            ws.Cells(r, 18).Value = rr    # R 人工费
            ws.Cells(r, 19).Value = s     # S 辅材费
            ws.Cells(r, 20).Value = t     # T 机械费
            for c in range(1, 22):
                ws.Cells(r, c).Interior.Color = 0xCCFFFF  # 母行全行标浅黄
            n_fill += 1
    wb.Save()
    print(f"已填 {n_fill} 条母行（P/Q/R/S/T）+ 整行标浅黄色")
except Exception as e:
    print("ERROR:", e)
finally:
    wb.Close(False)
    excel.Quit()
